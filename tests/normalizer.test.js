for (const c of cases) {
  const expected = c.edits.reduce((s, [from, to]) => {
    assert.ok(s.includes(from), `測試資料錯誤：找不到「${from}」`);
    return s.replace(from, to);
  }, c.input);

  test(c.name, () => {
    const r = normalize(c.input, opts);
    assert.equal(r.text, expected);
    assert.deepEqual(r.problems, []);
  });

  test(`${c.name}（重複整理結果不變）`, () => {
    const once = normalize(c.input, opts).text;
    const twice = normalize(once, opts);
    assert.equal(twice.text, once);
    assert.deepEqual(twice.problems, []);
  });
}

test("檢查器能抓到漏字與金額不符", () => {
  const input = "9/1（一）\n⚠️還書+100⚠️";
  assert.equal(normalize(input, opts).ok, true);
  const { check } = require("../assets/js/normalizer.js");
  assert.equal(check(input, "9/1（一）\n⚠️還+$100⚠️", []).ok, false);
  assert.equal(check(input, "9/1（一）\n⚠️還書+$200⚠️", []).ok, false);
});
